export function localizeServerError(message) {
  if (messages.has(message)) return messages.get(message);
  const fileSize = /^文件大小不能超过 ([\d.]+)MB$/.exec(message);
  const messageSize = /^消息过大，最大 ([\d.]+)KB$/.exec(message);
  if (fileSize) return `Le fichier ne doit pas dépasser ${fileSize[1]} Mo.`;
  if (messageSize) return `Le message ne doit pas dépasser ${messageSize[1]} Ko.`;
  return message;
}
